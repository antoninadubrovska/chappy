// clients message
const messageContentSchema = z.string().trim().min(1).max(2000);

export const guestMessageCreationSchema = z.object({
	username: z
		.string()
		.trim()
		.regex(
			/^Guest \d+$/,
			"Guest username must have the format Guest followed by a number",
		),
	content: messageContentSchema,
});
export type GuestMessageCreation = z.infer<typeof guestMessageCreationSchema>;

export const authenticatedMessageCreationSchema = z.object({
	content: messageContentSchema,
});
export type AuthenticatedMessageCreation = z.infer<
	typeof authenticatedMessageCreationSchema
>;

