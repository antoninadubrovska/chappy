import * as z from "zod";

// complete stored user, including the password hash
export const userSchema = z.object({
	userId: z.string(),
	username: z.string().min(3),
	displayName: z.string().min(1),
	passwordHash: z.string(),
	createdAt: z.string(),
});

export type User = z.infer<typeof userSchema>;

// information supplied during registration
export const userRegistrationSchema = z.object({
	username: z.string().trim().min(3),
	displayName: z.string().trim().min(1),
	password: z
		.string()
		.min(8, "Password must be at least 8 characters")
		.regex(/[A-Za-z]/, "Password must contain at least one letter")
		.regex(/[0-9]/, "Password must contain at least one number")
		.regex(
			/[^A-Za-z0-9]/,
			"Password must contain at least one special character",
		),
});

export type UserRegistration = z.infer<typeof userRegistrationSchema>;

// public user information returned by API
export const publicUserSchema = userSchema.omit({
	passwordHash: true,
});

export type PublicUser = z.infer<typeof publicUserSchema>;

// info supplied during login
export const loginCredentialsSchema = z.object({
	username: z.string().trim().min(3),
	password: z.string().min(8),
});

export type LoginCredentials = z.infer<typeof loginCredentialsSchema>;

// response returned after successful login
export type TokenResponse = {
	jwt: string;
};

// info stored inside JWT
export type JwtPayload = {
	userId: string;
};

// complete channel information
export const channelSchema = z.object({
	channelId: z.string(),
	name: z.string().trim().min(1),
	isLocked: z.boolean(),
	createdBy: z.string(),
	createdAt: z.string(),
});

export type Channel = z.infer<typeof channelSchema>;

// information supplied when creating a channel
// channelId, createdBy and createdAt are generated by the server
export const channelCreationSchema = channelSchema.omit({
	channelId: true,
	createdBy: true,
	createdAt: true,
});

export type ChannelCreation = z.infer<typeof channelCreationSchema>;

// describes how channel metadata is stored in DynamoDB
export const channelFromDbSchema = channelSchema.extend({
	pk: z.string(),
	sk: z.literal("META"),
	type: z.literal("CHANNEL"),
});

export type ChannelFromDb = z.infer<typeof channelFromDbSchema>;

// describes how a channel index record is stored in DynamoDB
export const channelIndexFromDbSchema = z.object({
	pk: z.literal("CHANNELS"),
	sk: z.string(),
	type: z.literal("CHANNEL_INDEX"),
	channelId: z.string(),
	name: z.string(),
	isLocked: z.boolean(),
});

export type ChannelIndexFromDb = z.infer<typeof channelIndexFromDbSchema>;

// message stored in DynamoDB

export const messageSchema = z.object({
	messageId: z.string(),
	channelId: z.string(),
	userId: z.string().nullable(),
	username: z.string().trim().min(1),
	content: z.string().trim().min(1).max(2000),
	createdAt: z.string(),
});

export type Message = z.infer<typeof messageSchema>;

